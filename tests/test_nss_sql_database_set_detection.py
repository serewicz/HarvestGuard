"""Regression coverage for HG-041 (GitHub issue #86): aggregate Mozilla NSS SQL
database-set inventory in the crypto-inventory scanner.

The bounded claim under test is exactly: *this lexical directory contains the
supported canonical NSS SQL database-set layout (`cert9.db`, `key4.db`,
`pkcs11.txt`) and a structurally recognized NSS internal-module configuration
stanza.* Nothing here asserts that either database is internally valid
SQLite/NSS data, that any certificate or key exists, that a key could be
unlocked, or that any application uses the directory.

The positive fixture in `fixtures/crypto_inventory/nss_sql/valid_empty/` was
generated by real `certutil -N` and its `pkcs11.txt` bytes are used verbatim --
never rewritten into a synthetic "preferred" layout (see that directory's
PROVENANCE.md). Synthetic markers appear only as negative controls, explicitly
allowed whitespace/case variants, duplicate-field cases, stanza-boundary
adversarial cases, and nested NSS-argument cases.
"""

