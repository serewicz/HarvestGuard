def _real_marker() -> bytes:
    """The committed, unmodified bytes real NSS tooling wrote."""
    return (NSS_FIXTURE / MARKER).read_bytes()


def _marker(
    library: str = "",
    name: str = VALID_NAME,
    parameters: str = VALID_PARAMETERS,
    nss: str = VALID_NSS,
) -> str:
    return (
        f"library={library}\n"
        f"name={name}\n"
        f"parameters={parameters}\n"
        f"NSS={nss}\n"
    )


def _root(
    tmp_path: Path,
    marker: str | bytes | None = "default",
    cert_db: bool = True,
    key_db: bool = True,
    name: str = "nssdb",
) -> Path:
    """A candidate lexical NSS root. `cert9.db`/`key4.db` stand in for real
    databases: HG-041 never opens them, so their content is irrelevant and
    deliberately not real NSS data."""
    root = tmp_path / name
    root.mkdir(parents=True, exist_ok=True)
    if marker is not None:
        data = _marker() if marker == "default" else marker
        if isinstance(data, str):
            (root / MARKER).write_text(data)
        else:
            (root / MARKER).write_bytes(data)
    if cert_db:
        (root / CERT_DB).write_bytes(b"SQLite format 3\x00 not-a-real-database")
    if key_db:
        (root / KEY_DB).write_bytes(b"SQLite format 3\x00 not-a-real-database")
    return root


def _real_root(tmp_path: Path, name: str = "nssdb") -> Path:
    """A root whose three files are the real `certutil -N` fixture bytes."""
    root = tmp_path / name
    root.mkdir(parents=True, exist_ok=True)
    for component in (MARKER, CERT_DB, KEY_DB):
        (root / component).write_bytes((NSS_FIXTURE / component).read_bytes())
    return root


def _records(path: Path, **kwargs) -> list[dict]:
    df = scan_crypto_inventory(str(path), **kwargs)
    return [] if df.empty else df.to_dict(orient="records")


def _nss_records(path: Path, **kwargs) -> list[dict]:
    return [r for r in _records(path, **kwargs) if r.get("Rule ID") == RULE_ID]


def _detector():
    return next(d for d in CRYPTO_DETECTORS if d.detector_id == RULE_ID)


