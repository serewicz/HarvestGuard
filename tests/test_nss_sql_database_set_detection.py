def test_evidence_store_round_trip_preserves_the_finding(tmp_path, capsys):
    """Real evidence-db scan -> verify -> JSON/Markdown export for HG-041."""
    target = tmp_path / "target"
    target.mkdir()
    root = _canary_root(target)
    db = tmp_path / "evidence.db"

    assert (
        harvestguard.main(
            [
                "scan",
                str(target),
                "--type",
                "crypto",
                "--json",
                "--quiet",
                "--evidence-db",
                str(db),
            ]
        )
        == 0
    )
    live = capsys.readouterr().out
    records = [r for r in json.loads(live) if r["rule_id"] == RULE_ID]
    assert len(records) == 1
    record = records[0]
    scan_id = record["scan_id"]
    assert scan_id
    assert record["source_type"] == "crypto_inventory"
    assert record["asset_type"] == ASSET_TYPE
    assert record["confidence"] == CONFIDENCE
    assert record["evidence"] == EVIDENCE
    assert record["technical_metadata"]["Format"] == FORMAT
    assert record["location"] == str(root)

    assert harvestguard.main(["evidence", "verify", scan_id, "--evidence-db", str(db)]) == 0
    capsys.readouterr()

    assert (
        harvestguard.main(
            ["evidence", "export", scan_id, "--evidence-db", str(db), "--json", "--quiet"]
        )
        == 0
    )
    stored = capsys.readouterr().out
    assert stored == live
    stored_record = [r for r in json.loads(stored) if r["rule_id"] == RULE_ID][0]
    assert stored_record["evidence"] == EVIDENCE
    metadata = stored_record["technical_metadata"]
    assert metadata["Format"] == FORMAT
    # Nothing beyond Format survives persistence: every other metadata key the
    # schema carries is unset for this finding.
    assert {k: v for k, v in metadata.items() if v is not None} == {"Format": FORMAT}

    assert (
        harvestguard.main(
            ["evidence", "export", scan_id, "--evidence-db", str(db), "--markdown", "--quiet"]
        )
        == 0
    )
    markdown = capsys.readouterr().out
    assert ASSET_TYPE in markdown
    assert EVIDENCE in markdown

    for payload in (live, stored, markdown):
        for canary in CANARIES:
            assert canary not in payload


