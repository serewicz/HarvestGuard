def test_directory_symlink_aliases_are_distinct_lexical_roots(tmp_path):
    target = tmp_path / "target"
    target.mkdir()
    real = _root(target, name="real")
    (target / "alias").symlink_to(real, target_is_directory=True)

    without = _nss_records(target)
    assert [r["Location"] for r in without] == [str(real)]

